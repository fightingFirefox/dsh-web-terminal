// Generates client-src/type-icons.tsx.
// File-type icons come from @iconify-json/vscode-icons (MIT).
// Bright/official brand logos come from simple-icons (CC0 1.0).
import icons from '@iconify-json/vscode-icons/icons.json' with { type: 'json' }
import * as si from 'simple-icons'
import { writeFile } from 'node:fs/promises'

// Official brand logos for categories where the file-type icon is unreadable.
const BRAND_MAP = {
  json: 'Json',
  yaml: 'Yaml',
}

const TYPE_MAP = {
  typescript: 'file-type-typescript',
  javascript: 'file-type-js',
  python: 'file-type-python',
  go: 'file-type-go',
  rust: 'file-type-rust',
  java: 'file-type-java',
  c: 'file-type-cpp',
  shell: 'file-type-shell',
  web: 'file-type-html',
  markdown: 'file-type-markdown',
  json: 'file-type-json',
  yaml: 'file-type-yaml',
}

function luminance(hex) {
  const r = parseInt(hex.slice(0, 2), 16) / 255
  const g = parseInt(hex.slice(2, 4), 16) / 255
  const b = parseInt(hex.slice(4, 6), 16) / 255
  const lin = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)
}

const typeEntries = {}
for (const [category, name] of Object.entries(TYPE_MAP)) {
  const icon = icons.icons[name]
  if (icon !== undefined) {
    typeEntries[category] = {
      title: name,
      width: icon.width ?? icons.width ?? 32,
      height: icon.height ?? icons.height ?? 32,
      body: icon.body,
    }
  }
}

const brandEntries = {}
for (const [category, slug] of Object.entries(BRAND_MAP)) {
  const icon = si['si' + slug]
  if (icon !== undefined) {
    brandEntries[category] = { title: icon.title, hex: icon.hex, path: icon.path }
  }
}

const lines = []
lines.push('// Generated by tools/gen-type-icons.mjs. Do not edit by hand.')
lines.push('// File-type icons: @iconify-json/vscode-icons (MIT). Official brand logos: simple-icons (CC0 1.0).')
lines.push('')
lines.push('export interface TypeIconData { title: string; width: number; height: number; body: string }')
lines.push('')
lines.push('export interface BrandIconData { title: string; hex: string; path: string }')
lines.push('')
lines.push('export const BRAND_ICONS: Record<string, BrandIconData> = {')
for (const [category, icon] of Object.entries(brandEntries)) {
  lines.push('  ' + category + ': { title: ' + JSON.stringify(icon.title) + ', hex: ' + JSON.stringify(icon.hex) + ', path: ' + JSON.stringify(icon.path) + ' },')
}
lines.push('}')
lines.push('')
lines.push('export const TYPE_ICONS: Record<string, TypeIconData> = {')
for (const [category, icon] of Object.entries(typeEntries)) {
  lines.push('  ' + category + ': { title: ' + JSON.stringify(icon.title) + ', width: ' + icon.width + ', height: ' + icon.height + ', body: ' + JSON.stringify(icon.body) + ' },')
}
lines.push('}')
lines.push('')
await writeFile(new URL('../client-src/type-icons.tsx', import.meta.url), lines.join('\n'), 'utf8')
console.log('type icons:', Object.keys(typeEntries).length)
